import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import dynamicIconImports from "lucide-react/dynamicIconImports";

const iconNames = Object.keys(dynamicIconImports).sort();
const spritePath = resolve("public/project-icons.svg");
const namesPath = resolve("src/lib/project-icon-names.ts");
const packageDir = dirname(fileURLToPath(import.meta.resolve("lucide-react/package.json")));
const license = (await readFile(resolve(packageDir, "LICENSE"), "utf8")).trim();
const importsSource = await readFile(fileURLToPath(import.meta.resolve("lucide-react/dynamicIconImports")), "utf8");
const iconFiles = new Map(
  [...importsSource.matchAll(/"([^"]+)": \(\) => import\('\.\/icons\/([^']+\.js)'\)/g)]
    .map(([, name, file]) => [name, file]),
);
if (iconFiles.size !== iconNames.length) throw new Error("Could not map every Lucide icon to its source file");

function escapeXml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;",
  })[character]);
}

function element([tag, attributes]) {
  const attrs = Object.entries(attributes)
    .filter(([name, value]) => name !== "key" && value != null)
    .map(([name, value]) => ` ${name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}="${escapeXml(value)}"`)
    .join("");
  return `<${tag}${attrs}/>`;
}

async function writeIfChanged(path, content) {
  try {
    if (await readFile(path, "utf8") === content) return;
  } catch {
    // First install has no generated asset yet.
  }
  await writeFile(path, content);
}

const symbols = [];
for (const name of iconNames) {
  const { __iconNode } = await import(`lucide-react/icons/${iconFiles.get(name).replace(/\.js$/, "")}`);
  if (!Array.isArray(__iconNode)) throw new Error(`Missing Lucide icon: ${name}`);
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${__iconNode.map(element).join("")}</symbol>`);
}

const sprite = [
  `<!--\n${license}\n-->`,
  '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true">',
  ...symbols,
  "</svg>",
  "",
].join("\n");
const manifest = [
  "// Generated by scripts/generate-project-icon-sprite.mjs from lucide-react.",
  `export const PROJECT_ICON_NAMES = ${JSON.stringify(iconNames)} as const;`,
  "",
].join("\n");

await Promise.all([writeIfChanged(spritePath, sprite), writeIfChanged(namesPath, manifest)]);
console.log(`[project icons] ${iconNames.length} icons available as static SVG symbols`);
