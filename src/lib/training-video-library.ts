export type TrainingVideo = {
  id: string;
  order: number;
  title: { ar: string; en: string };
  description: { ar: string; en: string };
  category: { ar: string; en: string };
  duration: string;
  seconds: number;
  src: string;
  thumbnail: string;
};

function video(
  order: number,
  id: string,
  seconds: number,
  duration: string,
  titleAr: string,
  titleEn: string,
  descriptionAr: string,
  descriptionEn: string,
  categoryAr: string,
  categoryEn: string,
): TrainingVideo {
  return {
    id,
    order,
    seconds,
    duration,
    title: { ar: titleAr, en: titleEn },
    description: { ar: descriptionAr, en: descriptionEn },
    category: { ar: categoryAr, en: categoryEn },
    src: `/training-videos/${id}.mp4`,
    thumbnail: `/training-videos/thumbnails/${id}.jpg`,
  };
}

